/// Tests whose result is a binary model, not a page: the dashboard shows the
/// prompt to copy, but can't run it, and the .glb is uploaded by hand.
const kBenchmarkManualKinds = {'cathedral'};

/// [kind]'s default prompt, with the output contract appended unless the
/// test is a manual one (its result is not an HTML page).
String benchmarkPromptFor(String kind) {
  final p = kBenchmarkPrompts[kind];
  if (p == null) return '';
  if (kBenchmarkManualKinds.contains(kind)) return p.prompt.trim();
  return '${p.prompt.trim()}$kBenchmarkOutputContract';
}

/// Every prompt as the files checked in under `benchmarks/prompts/`, for
/// running a test outside the dashboard: `<kind>.md` holds exactly what
/// "Add benchmark" sends, and `README.md` indexes them.
/// `dart run tool/export_benchmark_prompts.dart` writes them.
Map<String, String> benchmarkPromptFiles() {
  final files = <String, String>{};
  final index = StringBuffer()
    ..writeln('# Benchmark prompts')
    ..writeln()
    ..writeln('Generated from `server/lib/benchmark_prompts.dart` by')
    ..writeln('`dart run tool/export_benchmark_prompts.dart` (run in '
        '`server/`). Edit the')
    ..writeln('Dart file, not these, then re-run the export.')
    ..writeln()
    ..writeln('Each file is exactly what the admin dashboard\'s '
        '**Add benchmark** sends,')
    ..writeln('so a reply to it can be uploaded to the same test.')
    ..writeln()
    ..writeln('| Test | Kind | Prompt |')
    ..writeln('| --- | --- | --- |');
  for (final e in kBenchmarkPrompts.entries) {
    files['${e.key}.md'] = '${benchmarkPromptFor(e.key).trimRight()}\n';
    final note =
        kBenchmarkManualKinds.contains(e.key) ? ' (manual .glb upload)' : '';
    index.writeln(
        '| ${e.value.label}$note | `${e.key}` | [${e.key}.md](${e.key}.md) |');
  }
  files['README.md'] = index.toString();
  return files;
}

