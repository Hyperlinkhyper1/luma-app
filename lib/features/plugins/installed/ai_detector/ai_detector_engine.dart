/// The AI Detector's brain: a set of statistical writing-style checks that
/// estimate how machine-generated a piece of text reads.
///
/// There is deliberately no model here — no network, no embeddings, no
/// inference. Every signal is arithmetic on the words themselves, in the same
/// spirit as stylometry: LLM output tends to be *uniform* (steady sentence
/// lengths, tidy paragraphs, formal register) and leans on a recognisable
/// vocabulary. Humans are burstier and sloppier.
///
/// The one exception is the Claude watermark scan, which does not measure
/// style at all: it looks for the invisible characters and self-references a
/// generated text carries inside itself. Those can name an author outright,
/// which no statistic ever can, so a hit there promotes the verdict from
/// "AI-generated" to "Generated by Claude".
///
/// Each check produces an [AiTrigger] with a 0..1 strength, and the checks
/// come in two kinds that are scored very differently.
///
/// *Two-sided* checks measure rhythm — sentence-length spread, paragraph
/// spread, contractions, register — and a text can genuinely read human on
/// them, so they average both ways. Because formal human prose looks machine
/// uniform too, rhythm alone tops out below the highest band.
///
/// *One-way* checks (see [AiTrigger.oneWay]) look for things only generated
/// text tends to carry: a stock phrase, chat formatting, a corrective
/// contrast, a watermark. Finding one is evidence; finding none is not
/// evidence of a human hand, since most generated text carries no stock
/// phrase at all. These therefore only ever add to the score. Treating them
/// as two-sided was what let a fully generated essay score "mixed" — it
/// collected full-weight "human" votes simply for containing no em dashes
/// and no passive voice.
///
/// The two are combined the way independent suspicions combine, so either
/// can carry a verdict alone. Checks whose sample is too small to mean
/// anything stay out entirely rather than defaulting to "human". Every check
/// also reports the exact stretches of text it matched as [AiHighlight]s, so
/// the report can paint its evidence onto the source.
library;

import 'dart:math' as math;

/// One measured signal in the report.
class AiTrigger {
  const AiTrigger({
    required this.id,
    required this.title,
    required this.detail,
    required this.strength,
    this.evidence = const [],
    this.oneWay = false,
  });

  /// Stable identifier, e.g. `burstiness`.
  final String id;

  /// Short headline shown in the report list.
  final String title;

  /// One or two sentences explaining what was measured and why it matters.
  final String detail;

  /// 0..1 — how strongly this check fired. Below ~0.15 it counts as quiet.
  final double strength;

  /// Concrete proof pulled from the text: matched phrases, measured ranges,
  /// rates. Shown as chips under the trigger so the verdict can be checked.
  final List<String> evidence;

  /// True when this check can only ever *incriminate*.
  ///
  /// Finding a stock phrase, an em-dash storm or a watermark is evidence the
  /// text was generated. Finding none of them is not evidence it was not —
  /// plenty of generated text carries no stock phrase at all. A one-way
  /// check therefore adds to the score when it fires and abstains when it
  /// does not, instead of voting the score down the way a genuinely
  /// two-sided measurement can.
  final bool oneWay;

  bool get fired => strength >= 0.15;
}

/// Where a highlight came from. Each kind carries its own [severity] so the
/// renderer can paint a conclusive signature differently from a mild
/// stylistic tell, and so overlapping flags resolve to the stronger one.
enum AiHighlightKind {
  emDash('Em dash'),
  passive('Passive voice'),
  opener('Transition opener'),
  phrase('AI-favourite phrase'),
  assistant('Assistant boilerplate'),
  claudeName('Claude signature'),
  watermark('Claude watermark');

  const AiHighlightKind(this.label);

  /// Short name used in the highlight legend.
  final String label;

  /// 0 = mild stylistic tell, 1 = strong, 2 = conclusive.
  int get severity => switch (this) {
        AiHighlightKind.emDash ||
        AiHighlightKind.passive ||
        AiHighlightKind.opener =>
          0,
        AiHighlightKind.phrase || AiHighlightKind.assistant => 1,
        AiHighlightKind.claudeName || AiHighlightKind.watermark => 2,
      };
}

/// One stretch of the analysed text that a check flagged, so the report can
/// paint it in place instead of only describing it in a list.
class AiHighlight {
  const AiHighlight({
    required this.start,
    required this.end,
    required this.kind,
    required this.note,
  });

  /// UTF-16 offsets into the analysed text; [end] is exclusive.
  final int start;
  final int end;
  final AiHighlightKind kind;

  /// Why this stretch was flagged, shown in the legend and on hover.
  final String note;
}

/// Who the text is attributed to. Attribution only ever comes from a
/// signature the text carries itself — a hidden watermark character or a
/// self-reference. Style statistics alone can never name a model, so they
/// leave this at [AiAuthor.unknown].
enum AiAuthor { unknown, claude }

/// Everything the report page needs for one analysed text.
class AiDetectorReport {
  const AiDetectorReport({
    required this.score,
    required this.wordCount,
    required this.sentenceCount,
    required this.avgSentenceWords,
    required this.triggers,
    this.highlights = const [],
    this.author = AiAuthor.unknown,
  });

  /// 0..100 — higher reads more machine-like.
  final double score;
  final int wordCount;
  final int sentenceCount;
  final double avgSentenceWords;
  final List<AiTrigger> triggers;

  /// Every flagged stretch of the original text, merged and sorted by
  /// position, ready to paint straight onto the source.
  final List<AiHighlight> highlights;

  /// Set when the text signs itself — see [claudeSigned].
  final AiAuthor author;

  /// Short texts make every statistic meaningless; the UI shows a caution
  /// banner when this is false.
  bool get reliable => wordCount >= 60 && sentenceCount >= 4;

  /// True when the Claude watermark scan found something conclusive. That
  /// turns the verdict from a hedged "AI-generated" into a named
  /// attribution, because a signature identifies its writer where style
  /// statistics only ever describe one.
  bool get claudeSigned => author == AiAuthor.claude;

  /// Flagged stretches grouped by kind, for the highlight legend.
  Map<AiHighlightKind, int> get highlightCounts {
    final counts = <AiHighlightKind, int>{};
    for (final h in highlights) {
      counts[h.kind] = (counts[h.kind] ?? 0) + 1;
    }
    return counts;
  }

  String get verdict {
    if (claudeSigned) return 'Generated by Claude';
    if (score < 18) return 'Very likely human-written';
    if (score < 38) return 'Likely human-written';
    if (score < 58) return 'Mixed signals';
    if (score < 78) return 'Likely AI-generated';
    return 'Very likely AI-generated';
  }
}

