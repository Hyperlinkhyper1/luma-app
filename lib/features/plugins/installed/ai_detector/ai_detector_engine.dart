  static final _phraseRes = <String, RegExp>{
    for (final p in [..._strongPhrases, ..._softPhrases])
      p: RegExp('\\b${RegExp.escape(p)}\\b', caseSensitive: false),
  };

  static final _strongPhraseSet = _strongPhrases.toSet();

  /// The rhetorical shapes current models reach for when they want to sound
  /// insightful: the corrective contrast, the staged reveal, the pivot to
  /// "what's really going on". Humans write these too, just nowhere near as
  /// reliably, so they are counted as one more incriminating signal rather
  /// than treated as proof.
  static final _contrastRes = <String, RegExp>{
    '"not just X, but Y"': RegExp(
      r"\bnot (?:just|only|merely|simply)\b[^.!?\n]{0,90}?"
      r"\b(?:but|it(?:'s|’s| is))\b",
      caseSensitive: false,
    ),
    '"it’s not X. It’s Y."': RegExp(
      r"\b(?:it|this|that)(?:'s|’s| is)\s+not\s+"
      r'(?:about|that|a|the)\b[^.!?\n]{0,70}[.!?]\s+'
      r"(?:it|this|that)(?:'s|’s| is)\b",
      caseSensitive: false,
    ),
    '"isn’t just" construction': RegExp(
      r"\b(?:isn|aren|wasn|weren|doesn|don)(?:'|’)t\s+"
      r'(?:just|only|merely|simply|about)\b',
      caseSensitive: false,
    ),
    'staged reveal': RegExp(
      r'\bthe (?:real|actual|hard|interesting|important|key) '
      r'(?:question|problem|answer|issue|part|insight|point|reason)\b',
      caseSensitive: false,
    ),
    '"that’s the point" close': RegExp(
      r"\bthat(?:'s|’s| is) (?:the|exactly the|precisely the) "
      r'(?:point|whole point|key|catch|trick|difference)\b',
      caseSensitive: false,
    ),
    '"here’s the thing" pivot': RegExp(
      r"\bhere(?:'s|’s| is) (?:the thing|the catch|where|why|what)\b",
      caseSensitive: false,
    ),
  };

  /// Scaffolding that survives a copy-paste out of a chat window: markdown
  /// headings, bullet runs, numbered steps, and the bolded "Label: text"
  /// list item that chat models format almost every answer with.
  static final _headingRe = RegExp(r'^\s{0,3}#{1,6}\s+\S', multiLine: true);
  static final _bulletRe =
      RegExp(r'^\s{0,6}(?:[-*•‣◦]|\d{1,2}[.)])\s+\S',
